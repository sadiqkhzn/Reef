import AppKit
import SwiftUI

/// A SwiftUI wrapper around `NSVisualEffectView`.
///
/// Used for the frosted island material. Blending behind the window blurs the
/// desktop and apps underneath the overlay panel. The view is kept active so
/// the blur stays live even though the panel never becomes key.
struct VisualEffectBlur: NSViewRepresentable {
    var material: NSVisualEffectView.Material = .hudWindow
    var blendingMode: NSVisualEffectView.BlendingMode = .behindWindow

    func makeNSView(context: Context) -> NSVisualEffectView {
        let view = NSVisualEffectView()
        view.state = .active
        view.isEmphasized = false
        apply(to: view)
        return view
    }

    func updateNSView(_ view: NSVisualEffectView, context: Context) {
        apply(to: view)
    }

    private func apply(to view: NSVisualEffectView) {
        view.material = material
        view.blendingMode = blendingMode
    }
}
